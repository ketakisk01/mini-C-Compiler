#include "Parser.h"
#include <iostream>

// =====================================================
// Parse Tree Printing
// =====================================================

void ParseTreeNode::print(int indent) const
{
    for (int i = 0; i < indent; i++)
        std::cout << "  ";

    std::cout << "|-- " << name << "\n";

    for (const auto& child : children)
    {
        if (child)
            child->print(indent + 1);
    }
}


// =====================================================
// Constructor
// =====================================================

Parser::Parser(
    const std::vector<Token>& tokenList,
    SymbolTable& table
)
    : tokens(tokenList),
      current(0),
      symbolTable(table)
{
    parseTreeRoot =
        std::make_shared<ParseTreeNode>("Program");

    lastTreeNode = nullptr;
}


// =====================================================
// Token Helpers
// =====================================================

Token& Parser::peek()
{
    return const_cast<Token&>(tokens[current]);
}

Token& Parser::previous()
{
    return const_cast<Token&>(tokens[current - 1]);
}

bool Parser::check(TokenType type)
{
    return peek().type == type;
}

bool Parser::match(TokenType type)
{
    if (check(type))
    {
        current++;
        return true;
    }

    return false;
}

Token Parser::consume(
    TokenType type,
    const std::string& message
)
{
    if (check(type))
        return tokens[current++];

    syntaxError(message);

    return Token(
        TokenType::INVALID,
        "",
        peek().line,
        peek().column
    );
}


// =====================================================
// Syntax Error
// =====================================================

void Parser::syntaxError(
    const std::string& message
)
{
    std::cerr
        << "Syntax Error at line "
        << peek().line
        << ", column "
        << peek().column
        << ": "
        << message
        << "\n";
}


// =====================================================
// Program
// =====================================================

std::shared_ptr<ProgramNode> Parser::parse()
{
    auto program =
        std::make_shared<ProgramNode>();

    while (!check(TokenType::END_OF_FILE))
    {
        ASTPtr statement = parseStatement();

        if (statement)
            program->statements.push_back(statement);

        // Add the parse tree generated by
        // this statement to Program.
        if (lastTreeNode)
        {
            parseTreeRoot->addChild(lastTreeNode);
            lastTreeNode = nullptr;
        }
    }

    return program;
}


// =====================================================
// Statement
// =====================================================

ASTPtr Parser::parseStatement()
{
    if (check(TokenType::BREW))
        return parseDeclaration();

    if (check(TokenType::IF))
        return parseIf();

    if (check(TokenType::WHILE))
        return parseWhile();

    if (check(TokenType::SERVE))
        return parseServe();

    if (check(TokenType::SIP))
        return parseSip();

    if (check(TokenType::RETURN))
        return parseReturn();

    if (check(TokenType::LEFT_BRACE))
        return parseBlock();

    if (check(TokenType::IDENTIFIER))
        return parseAssignment();

    syntaxError(
        "Unexpected token '" +
        peek().lexeme +
        "'"
    );

    current++;
    lastTreeNode = nullptr;

    return nullptr;
}


// =====================================================
// Declaration
// =====================================================

ASTPtr Parser::parseDeclaration()
{
    auto node =
        std::make_shared<ParseTreeNode>(
            "Declaration"
        );

    Token brew =
        consume(
            TokenType::BREW,
            "Expected 'brew'"
        );

    node->addChild(
        std::make_shared<ParseTreeNode>(
            "brew"
        )
    );

    // Optional data type
    if (check(TokenType::INT_TYPE) ||
        check(TokenType::FLOAT_TYPE) ||
        check(TokenType::CHAR_TYPE) ||
        check(TokenType::BOOL_TYPE) ||
        check(TokenType::STRING_TYPE))
    {
        Token typeToken = tokens[current++];

        node->addChild(
            std::make_shared<ParseTreeNode>(
                "Type: " + typeToken.lexeme
            )
        );
    }

    Token name =
        consume(
            TokenType::IDENTIFIER,
            "Expected variable name after 'brew'"
        );

    node->addChild(
        std::make_shared<ParseTreeNode>(
            "Identifier: " + name.lexeme
        )
    );

    symbolTable.addSymbol(
        name.lexeme,
        "variable",
        name.line
    );

    ASTPtr initializer = nullptr;

    if (match(TokenType::ASSIGN))
    {
        node->addChild(
            std::make_shared<ParseTreeNode>("=")
        );

        initializer = parseExpression();

        // parseExpression created lastTreeNode
        node->addChild(lastTreeNode);
    }

    consume(
        TokenType::SEMICOLON,
        "Expected ';' after declaration"
    );

    node->addChild(
        std::make_shared<ParseTreeNode>(";")
    );

    lastTreeNode = node;

    return std::make_shared<DeclarationNode>(
        name.lexeme,
        initializer
    );
}


// =====================================================
// Assignment
// =====================================================

ASTPtr Parser::parseAssignment()
{
    auto node =
        std::make_shared<ParseTreeNode>(
            "Assignment"
        );

    Token name =
        consume(
            TokenType::IDENTIFIER,
            "Expected identifier"
        );

    node->addChild(
        std::make_shared<ParseTreeNode>(
            "Identifier: " + name.lexeme
        )
    );

    consume(
        TokenType::ASSIGN,
        "Expected '=' after identifier"
    );

    node->addChild(
        std::make_shared<ParseTreeNode>("=")
    );

    ASTPtr expression =
        parseExpression();

    node->addChild(lastTreeNode);

    consume(
        TokenType::SEMICOLON,
        "Expected ';' after assignment"
    );

    node->addChild(
        std::make_shared<ParseTreeNode>(";")
    );

    lastTreeNode = node;

    return std::make_shared<AssignmentNode>(
        name.lexeme,
        expression
    );
}


// =====================================================
// IF
// =====================================================

ASTPtr Parser::parseIf()
{
    auto node =
        std::make_shared<ParseTreeNode>(
            "IfStatement"
        );

    consume(
        TokenType::IF,
        "Expected 'if'"
    );

    node->addChild(
        std::make_shared<ParseTreeNode>("if")
    );

    consume(
        TokenType::LEFT_PAREN,
        "Expected '(' after 'if'"
    );

    node->addChild(
        std::make_shared<ParseTreeNode>("(")
    );

    ASTPtr condition =
        parseExpression();

    node->addChild(lastTreeNode);

    consume(
        TokenType::RIGHT_PAREN,
        "Expected ')' after condition"
    );

    node->addChild(
        std::make_shared<ParseTreeNode>(")")
    );

    ASTPtr thenBranch =
        parseStatement();

    node->addChild(lastTreeNode);

    ASTPtr elseBranch = nullptr;

    if (match(TokenType::ELSE))
    {
        node->addChild(
            std::make_shared<ParseTreeNode>("else")
        );

        elseBranch =
            parseStatement();

        node->addChild(lastTreeNode);
    }

    lastTreeNode = node;

    return std::make_shared<IfNode>(
        condition,
        thenBranch,
        elseBranch
    );
}


